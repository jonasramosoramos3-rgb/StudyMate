#!/usr/bin/env node
/*
 * Builds standalone/index.html - one self-contained file with the accounting
 * engine and UI inlined. No build step is needed to use the app; this just
 * regenerates the single-file bundle from its sources.
 *
 *   node tools/build-standalone.js          # write standalone/index.html
 *   node tools/build-standalone.js --check  # exit 1 if the file is stale
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const read = p => fs.readFileSync(path.join(ROOT, p), "utf8");

function build() {
  const engine = read("accounting.js");
  const style = read("standalone/src/style.css");
  const app = read("standalone/src/app.js");
  const version = JSON.parse(read("package.json")).version;

  // guard against accidentally closing the inline script tag early
  [engine, app].forEach((src, i) => {
    if (/<\/script/i.test(src)) throw new Error(`source ${i} contains a literal </script - escape it as <\\/script`);
  });

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Financial Statement Machine - journal to financial statements, offline</title>
<meta name="description" content="Paste or drop a journal table (CSV, TXT or Excel) and get the general ledger, trial balance, worksheet, income statement, statement of changes in equity, balance sheet and statement of cash flows - direct and indirect methods. One file, works offline, nothing is uploaded.">
<meta name="theme-color" content="#4f46e5">
<!--
  Generated by tools/build-standalone.js from:
    accounting.js            (engine - shared with the StudyMate app)
    standalone/src/style.css
    standalone/src/app.js
  Do not edit this file directly; edit the sources and rebuild.
  Build: v${version}
-->
<script src="https://cdnjs.cloudflare.com/ajax/libs/jszip/3.10.1/jszip.min.js" onerror="window.__jszipMissing=true"></script>
<style>
${style}
</style>
</head>
<body>
<noscript><p style="font:15px system-ui;padding:24px">This tool runs entirely in your browser, so JavaScript needs to be enabled. Nothing is uploaded either way.</p></noscript>
<script>
${engine}
</script>
<script>
${app}
</script>
</body>
</html>
`;
}

if (require.main === module) {
  const out = build();
  const target = path.join(ROOT, "standalone", "index.html");
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
    if (current !== out) {
      console.error("standalone/index.html is stale - run: node tools/build-standalone.js");
      process.exit(1);
    }
    console.log("standalone/index.html is up to date (" + out.length + " bytes)");
  } else {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, out);
    console.log("wrote standalone/index.html (" + out.length + " bytes)");
  }
}

module.exports = { build };
